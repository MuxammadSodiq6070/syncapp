class AppLocale extends ChangeNotifier {
  static final AppLocale instance = AppLocale._();
  AppLocale._();

  String _selectedCode = 'auto';
  String _resolvedCode = 'en';

  String get selectedCode => _selectedCode;
  String get resolvedCode => _resolvedCode;
  bool get isAuto => _selectedCode == 'auto';

  static const _storage = FlutterSecureStorage();
  static const _prefKey = 'sync_app_language_pref';

  String get currentLanguageName {
    final lang = allGoogleTranslateLanguages.firstWhere(
      (l) => l.code == _resolvedCode,
      orElse: () => allGoogleTranslateLanguages.first,
    );
    return lang.displayName;
  }

  Future<void> init() async {
    try {
      final saved = await _storage.read(key: _prefKey);
      if (saved != null && saved.isNotEmpty) {
        _selectedCode = saved;
      } else {
        _selectedCode = 'auto';
      }
    } catch (_) {
      _selectedCode = 'auto';
    }
    _resolve();
  }

  void _resolve() {
    if (_selectedCode != 'auto') {
      _resolvedCode = _selectedCode;
      return;
    }
    final locale = PlatformDispatcher.instance.locale;
    final lang = locale.languageCode.toLowerCase();
    final country = locale.countryCode?.toUpperCase();

    if (lang == 'uz' || country == 'UZ') {
      _resolvedCode = 'uz';
    } else if (lang == 'ru' || country == 'RU') {
      _resolvedCode = 'ru';
    } else if (lang == 'tr' || country == 'TR') {
      _resolvedCode = 'tr';
    } else if (lang == 'es') {
      _resolvedCode = 'es';
    } else if (lang == 'de') {
      _resolvedCode = 'de';
    } else if (lang == 'fr') {
      _resolvedCode = 'fr';
    } else if (lang == 'ar' || country == 'SA' || country == 'AE') {
      _resolvedCode = 'ar';
    } else if (lang == 'zh') {
      _resolvedCode = 'zh';
    } else if (lang == 'kk' || country == 'KZ') {
      _resolvedCode = 'kk';
    } else if (lang == 'tg' || country == 'TJ') {
      _resolvedCode = 'tg';
    } else if (lang == 'ky' || country == 'KG') {
      _resolvedCode = 'ky';
    } else {
      _resolvedCode = 'en';
    }
  }

  Future<void> setLanguage(String code) async {
    _selectedCode = code;
    _resolve();
    try {
      await _storage.write(key: _prefKey, value: code);
    } catch (_) {}
    notifyListeners();
  }

  String translate(String key) {
    final dict = _dictionaries[_resolvedCode] ?? _dictionaries['en']!;
    return dict[key] ?? _dictionaries['en']?[key] ?? key;
  }
}

String tr(String key) => AppLocale.instance.translate(key);

/// Fills the %s placeholders of a translated string, in order. Keeping the
/// placeholder in the table rather than splitting the sentence lets each language
/// put the name where its own grammar wants it.
String trp(String key, List<String> values) {
  var out = tr(key);
  for (final v in values) {
    out = out.replaceFirst('%s', v);
  }
  return out;
}

